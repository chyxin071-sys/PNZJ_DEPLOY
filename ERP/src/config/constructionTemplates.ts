export interface SubNodeField { label: string; key: string; unit?: string; }
export interface SubNodeConfig {
  name: string;
  type: string;
  requirePhoto: boolean;
  requireSign?: boolean;
  fields?: SubNodeField[];
  standard?: string;
  standardPublic?: boolean;
  checklist?: string[];
}
export interface SectionConfig { name: string; nodes: SubNodeConfig[]; }
export interface Craftsmanship { text: string; images?: string[]; }
export interface StageConfig { name: string; craftsmanship?: Craftsmanship[]; sections: SectionConfig[]; }

export interface CraftTemplate {
  id: string;
  name: string;
  description: string;
  stages: StageConfig[];
}

export function makeId() { return Date.now().toString(36) + Math.random().toString(36).slice(2, 9); }

export const DEFAULT_NODE_TYPE = '普通工序';

const TYPE_NORMALIZE_MAP: Record<string, string> = {
  '重点验收': '重点验收',
  '隐蔽验收': '重点验收',
  '验收清单': '重点验收',
  '普通工序': '普通工序',
  '施工标准告知': '普通工序',
  '材料进场': '材料进场',
};

export function normalizeNodeType(type?: string) {
  return TYPE_NORMALIZE_MAP[type || ''] || DEFAULT_NODE_TYPE;
}

const SN = (name: string, extra?: Partial<SubNodeConfig>): SubNodeConfig => ({
  name, type: '普通工序', requirePhoto: true, ...extra,
});
const SH = (name: string, standard: string, extra?: Partial<SubNodeConfig>): SubNodeConfig => ({
  name, type: '重点验收', requirePhoto: true, standard, standardPublic: true, ...extra,
});
const ST = (name: string, standard: string, extra?: Partial<SubNodeConfig>): SubNodeConfig => ({
  name, type: '普通工序', requirePhoto: false, standard, standardPublic: true, ...extra,
});
const CL = (name: string, checklist: string[], extra?: Partial<SubNodeConfig>): SubNodeConfig => ({
  name, type: '重点验收', requirePhoto: true, checklist, ...extra,
});

