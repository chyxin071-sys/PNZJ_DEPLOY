export const DEFAULT_TEMPLATES: CraftTemplate[] = [roughHouse, oldHouse];

const STORAGE_KEY = 'pnzj_craft_templates';

export function loadTemplates(): CraftTemplate[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch { /* ignore */ }
  return JSON.parse(JSON.stringify(DEFAULT_TEMPLATES));
}

export function saveTemplates(templates: CraftTemplate[]) {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(templates));
}

export function getTemplates(): CraftTemplate[] {
  return loadTemplates();
}

export function getTemplateById(id: string): CraftTemplate | undefined {
  return loadTemplates().find(t => t.id === id);
}

export function buildNodesFromTemplate(template: CraftTemplate | null | undefined) {
  if (!template || !template.stages) return [];
  return template.stages.map(stage => ({
    _id: makeId(),
    name: stage.name,
    collapsed: false,
    craftsmanship: stage.craftsmanship ? JSON.parse(JSON.stringify(stage.craftsmanship)) : [],
    sections: stage.sections.map(sec => ({
      _id: makeId(),
      name: sec.name,
      collapsed: false,
      subNodes: sec.nodes.map((n, idx) => ({
        _id: makeId(),
        name: n.name,
        type: n.type,
        requirePhoto: n.requirePhoto,
        requireSign: n.requireSign || false,
        fields: n.fields || [],
        standard: n.standard || '',
        standardPublic: n.standardPublic !== false,
        checklist: n.checklist || [],
        order: idx,
        completed: false,
        completedAt: null,
        completedBy: null,
        photos: [],
      })),
    })),
  }));
}

